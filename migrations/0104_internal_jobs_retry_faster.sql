-- 0104: повтор внутренних работ — растущая пауза от минуты до часа [Р-133, шаг 28; уточнение Р-132]
--
-- Р-132 (шаг 27) сделал паузу повтора не короче периода работы: канал, который лежит, не должен получать запрос каждую минуту.
-- Но у внутренних работ (выгрузка в ClickHouse, удаление по сроку, закрытие суток, секции) лимитов канала нет, а период — сутки или
-- час. Живой прогон шага 27 это и показал: отказ аналитического слоя стоил суток истории снимков, потому что повтор ушёл на следующий
-- суточный слот. Р-133: у внутренних работ пауза растёт от минуты до часа — за 14 попыток отказа слоя история теряется, а не за 14 суток.
--
-- Вид повтора — свойство работы, и хранится он в базе: сроки считает планировщик по состоянию работы, а не по коду, который мог
-- разойтись с тем, что уже зарегистрировано.

BEGIN;

SET ROLE repracer_owner;

ALTER TABLE maintenance.scheduled_job ADD COLUMN retry_kind text NOT NULL DEFAULT 'CHANNEL'
  CONSTRAINT scheduled_job_retry_kind_known CHECK (retry_kind IN ('CHANNEL', 'INTERNAL'));
COMMENT ON COLUMN maintenance.scheduled_job.retry_kind IS
  'Шаг 28 [Р-133]: CHANNEL — пауза повтора не короче периода работы (лимиты канала); INTERNAL — растущая пауза от минуты до часа';

-- Работы, которые ходят только в наши хранилища: у них лимитов канала нет
UPDATE maintenance.scheduled_job SET retry_kind = 'INTERNAL'
 WHERE job_name IN ('analytics-export-day', 'price-days-close', 'partitions', 'retention');

RESET ROLE;

COMMIT;
