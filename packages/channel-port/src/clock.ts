import type { Instant } from './primitives.ts';

/**
 * Шаг 56 (п. 6): ЕДИНСТВЕННОЕ место, где код продукта читает настоящие часы. Время — зависимость (`now`) у пути решения, работ,
 * заданий, транспортов, стражей; `systemClock` — только их умолчание. Стенд и живые прогоны подставляют свои часы — поэтому исход
 * проверки не зависит от того, когда её запустили (правило репозитория «настоящие часы — только с пометкой»)
 */
export const systemClock = {
  now: (): Instant => new Date().toISOString(), // real-clock: единственный источник настоящих часов кода продукта
  nowMs: (): number => Date.now(), // real-clock: единственный источник настоящих часов кода продукта
};
