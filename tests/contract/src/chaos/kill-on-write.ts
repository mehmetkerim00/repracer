/**
 * Шаг 113 (полный прогон 41700831667, семя 1816539284): утверждение «диспетчер убит в момент записи» — событие, а не намерение плана
 * (ревью шага 65, находка 3). Но событие вероятностное: жребий тянется на КАЖДУЮ применённую запись, пока диспетчер жив и напечатал
 * готовность, и убивает с долей раунда. Прежнее условие «доля есть и записей за весь прогон больше 20» требовало события и тогда, когда
 * шансов было мало: доля 0,17 была только в раунде 1, к его концу — 19 записей, часть — при убитом диспетчере; промах — около 3 %, и прогон
 * краснел при чистых инвариантах всех раундов. Событие обязано случиться, только когда промах почти невозможен: произведение
 * (1 − доля) по каждому шансу раунда — меньше одной тысячной
 */
export interface KillOnWriteRound {
  /** Доля убийства в момент записи в раунде */
  share: number;
  /** Сколько раз тянулся жребий: применённая запись при живом и готовом диспетчере */
  chances: number;
}

export const KILL_ON_WRITE_MISS_LIMIT = 0.001;

/** Вероятность, что за все шансы всех раундов не случилось ни одного убийства в момент записи */
export function killOnWriteMissProbability(rounds: readonly KillOnWriteRound[]): number {
  return rounds.reduce((p, r) => p * (r.share > 0 ? (1 - r.share) ** r.chances : 1), 1);
}

/** Обязано ли событие случиться: промах при таких шансах почти невозможен */
export function killOnWriteExpected(rounds: readonly KillOnWriteRound[]): boolean {
  return killOnWriteMissProbability(rounds) < KILL_ON_WRITE_MISS_LIMIT;
}
